// plugins/subagent-router/node/worker.cjs
// Bundle-side Node worker (JSON-RPC 2.0 over stdio). stdout carries protocol
// messages only; diagnostics go to stderr.
//
// Owns two things on the host:
//   1. the extension package written to <cindyHome>/cindy-extensions/subagent-router/
//   2. the local-path entry inside <cindyHome>/pi-package-home/settings.json
// Every method is idempotent: calling install twice writes nothing new, calling
// uninstall twice reports "nothing to do" and leaves no files behind.
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { randomUUID } = require('node:crypto');

const EXT_ID = 'subagent-router';
const EXT_VERSION = require('../ghost.json').version;
const SETTINGS_FILE = 'settings.json';
const PKG_HOME = 'pi-package-home';

const EXT_INDEX = String.raw`
// subagent-router extension (generated by the Cindy plugin; do not edit by hand).
import { readFileSync, statSync } from "node:fs";

const CONFIG_URL = new URL("./config.json", import.meta.url);
const RETRYABLE_ROLES = new Set(["scout", "reviewer", "planner"]);
const DEFAULTS = { version: 1, enabled: true, defaultGroupId: "", groups: [] };
let cache = { mtimeMs: 0, config: DEFAULTS };

function readConfig() {
  try {
    const st = statSync(CONFIG_URL);
    if (st.mtimeMs === cache.mtimeMs) return cache.config;
    cache = { mtimeMs: st.mtimeMs, config: normalize(JSON.parse(readFileSync(CONFIG_URL, "utf8"))) };
    return cache.config;
  } catch {
    return DEFAULTS;
  }
}

function normalize(raw) {
  const out = { ...DEFAULTS, ...(raw && typeof raw === "object" ? raw : {}) };
  out.groups = Array.isArray(out.groups)
    ? out.groups
        .filter((g) => g && typeof g === "object" && Array.isArray(g.models))
        .map((g) => ({
          id: String(g.id || ""),
          name: String(g.name || g.id || ""),
          description: String(g.description || ""),
          models: g.models
            .filter((m) => m && typeof m === "object" && typeof m.id === "string" && m.id)
            .map((m) => ({ id: m.id, provider: typeof m.provider === "string" ? m.provider : undefined, name: String(m.name || m.id) })),
        }))
    : [];
  out.enabled = out.enabled !== false;
  return out;
}

function chainFor(config) {
  if (!config.enabled) return [];
  const group = config.groups.find((g) => g.id === config.defaultGroupId) || config.groups.find((g) => g.models.length > 0);
  return group ? group.models.map((m) => ({ model: m.id, provider: m.provider })) : [];
}

export default function (pi) {
  pi.on?.("tool_call", async (event) => {
    if (!event || event.toolName !== "subagent") return;
    const input = event.input;
    if (!input || typeof input !== "object") return;
    if (typeof input.action === "string" && input.action !== "run") return;
    const chain = chainFor(readConfig());
    if (!chain.length) return;
    const first = chain[0];
    if (Array.isArray(input.tasks)) {
      for (const task of input.tasks) {
        if (!task || typeof task !== "object" || task.model) continue;
        task.model = first.model;
        if (first.provider && !task.provider) task.provider = first.provider;
      }
      return;
    }
    if (!input.model) input.model = first.model;
    if (first.provider && !input.provider) input.provider = first.provider;
  });

  pi.registerTool?.({
    name: "delegate",
    description:
      "Delegate one assignment to a subagent with automatic model fallback: walks the configured model chain and moves on only when the model/provider layer fails (unavailable, 429, 5xx, timeout). Roles: scout | reviewer | planner | worker.",
    parameters: {
      type: "object",
      properties: {
        agent: { type: "string", description: "scout | reviewer | planner | worker" },
        task: { type: "string", description: "The exact assignment." },
        title: { type: "string", description: "Optional short label." },
      },
      required: ["agent", "task"],
    },
    execute: async (toolCallId, params, _signal, onUpdate, ctx) => {
      const agent = String(params?.agent || "");
      const task = String(params?.task || "");
      if (!task) throw new Error("delegate: task is required");
      const chain = chainFor(readConfig());
      if (!chain.length) throw new Error("delegate: no model configured");
      const steps = RETRYABLE_ROLES.has(agent) ? chain : chain.slice(0, 1);
      const failures = [];
      for (let i = 0; i < steps.length; i += 1) {
        const step = steps[i];
        if (onUpdate) onUpdate({ text: "delegate: trying " + step.model + " (" + (i + 1) + "/" + steps.length + ")" });
        try {
          const res = await ctx.executeTool("subagent", {
            agent,
            task,
            ...(params?.title ? { title: String(params.title) } : {}),
            model: step.model,
            ...(step.provider ? { provider: step.provider } : {}),
          });
          if (res && res.isError) throw new Error("subagent failed");
          return res;
        } catch (err) {
          failures.push(step.model + ": " + ((err && err.message) || err));
        }
      }
      throw new Error("delegate: every model failed -> " + failures.join(" | "));
    },
  });
}
`;

const EXT_PACKAGE = JSON.stringify(
  { name: 'cindy-subagent-router', version: EXT_VERSION, private: true, keywords: ['pi-package'], type: 'module', pi: { extensions: ['./index.js'] } },
  null,
  2,
);

const EMPTY_CONFIG = {
  version: 1,
  enabled: true,
  defaultGroupId: '',
  groups: [],
};

function reply(message) {
  process.stdout.write(JSON.stringify(message) + '\n');
}

function log(text) {
  process.stderr.write('[subagent-router] ' + text + '\n');
}

// ---------------------------------------------------------------------------
// path discovery (multi-platform; never guess-write outside a verified root)
// ---------------------------------------------------------------------------
function cindyHomeCandidates() {
  const home = os.homedir();
  const out = [];
  if (process.env.CINDY_HOME) out.push(process.env.CINDY_HOME);
  if (process.env.APPDATA) out.push(path.join(process.env.APPDATA, 'CindyGlobal'));
  if (process.platform === 'darwin') out.push(path.join(home, 'Library', 'Application Support', 'CindyGlobal'));
  if (process.env.XDG_CONFIG_HOME) out.push(path.join(process.env.XDG_CONFIG_HOME, 'CindyGlobal'));
  out.push(path.join(home, '.config', 'CindyGlobal'));
  out.push(path.join(home, 'AppData', 'Roaming', 'CindyGlobal'));
  return [...new Set(out)];
}

function resolveHome() {
  for (const candidate of cindyHomeCandidates()) {
    try {
      if (!fs.existsSync(candidate) || !fs.statSync(candidate).isDirectory()) continue;
      // A Cindy home is only trusted when it carries the package home we manage.
      if (fs.existsSync(path.join(candidate, PKG_HOME))) return candidate;
    } catch (_) {
      /* ignore unreadable candidates */
    }
  }
  return null;
}

function pathsFor(home) {
  const extDir = path.join(home, 'cindy-extensions', EXT_ID);
  return {
    home,
    extDir,
    extIndex: path.join(extDir, 'index.js'),
    extPackage: path.join(extDir, 'package.json'),
    extConfig: path.join(extDir, 'config.json'),
    settings: path.join(home, PKG_HOME, SETTINGS_FILE),
  };
}

function toPosix(value) {
  return String(value).replace(/\\/g, '/');
}

function samePath(a, b) {
  const left = toPosix(a).replace(/\/+$/, '');
  const right = toPosix(b).replace(/\/+$/, '');
  if (process.platform === 'linux') return left === right;
  return left.toLowerCase() === right.toLowerCase();
}

// ---------------------------------------------------------------------------
// settings.json (owned by Cindy; we do a minimal read/modify/atomic-write)
// ---------------------------------------------------------------------------
function readSettings(file) {
  if (!fs.existsSync(file)) return { exists: false, json: { packages: [] }, raw: null };
  const raw = fs.readFileSync(file, 'utf8');
  let json;
  try {
    json = JSON.parse(raw);
  } catch (err) {
    throw new Error('settings.json 不是合法 JSON，已中止以免覆盖：' + err.message);
  }
  if (!json || typeof json !== 'object' || Array.isArray(json)) json = { packages: [] };
  if (!Array.isArray(json.packages)) json.packages = [];
  return { exists: true, json, raw };
}

function writeSettingsAtomic(file, json) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = file + '.tmp-' + randomUUID();
  fs.writeFileSync(tmp, JSON.stringify(json, null, 2) + '\n', 'utf8');
  fs.renameSync(tmp, file);
}

function injectEntry(file, extDir) {
  const state = readSettings(file);
  const norm = toPosix(extDir);
  const existing = state.json.packages.filter((entry) => typeof entry === 'string' && samePath(entry, extDir));
  // Exactly one entry, already in the canonical form: nothing to write.
  if (existing.length === 1 && existing[0] === norm) return { changed: false };
  const kept = state.json.packages.filter((entry) => !(typeof entry === 'string' && samePath(entry, extDir)));
  kept.push(norm);
  state.json.packages = kept;
  writeSettingsAtomic(file, state.json);
  return { changed: true };
}

function removeEntry(file, extDir) {
  if (!fs.existsSync(file)) return { changed: false };
  const state = readSettings(file);
  const before = state.json.packages.length;
  state.json.packages = state.json.packages.filter((entry) => !(typeof entry === 'string' && samePath(entry, extDir)));
  if (state.json.packages.length === before) return { changed: false };
  writeSettingsAtomic(file, state.json);
  return { changed: true };
}

// ---------------------------------------------------------------------------
// idempotent file materialisation
// ---------------------------------------------------------------------------
function ensureFile(file, content) {
  try {
    if (fs.readFileSync(file, 'utf8') === content) return false;
  } catch (_) {
    /* missing: write below */
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = file + '.tmp-' + randomUUID();
  fs.writeFileSync(tmp, content, 'utf8');
  fs.renameSync(tmp, file);
  return true;
}

function readConfigFile(file) {
  try {
    const parsed = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) return null;
    return parsed;
  } catch (_) {
    return null;
  }
}

function sanitizeConfig(input) {
  const groupList = Array.isArray(input?.groups) ? input.groups : [];
  const seen = new Set();
  const groups = [];
  for (const raw of groupList.slice(0, 20)) {
    if (!raw || typeof raw !== 'object') continue;
    const id = String(raw.id || '').trim().slice(0, 40);
    if (!/^[a-z0-9][a-z0-9-]*$/.test(id) || seen.has(id)) continue;
    seen.add(id);
    const models = [];
    const modelSeen = new Set();
    for (const m of Array.isArray(raw.models) ? raw.models.slice(0, 30) : []) {
      if (!m || typeof m !== 'object') continue;
      const mid = String(m.id || '').trim().slice(0, 120);
      if (!mid || modelSeen.has(mid)) continue;
      modelSeen.add(mid);
      models.push({
        id: mid,
        ...(m.provider ? { provider: String(m.provider).trim().slice(0, 60) } : {}),
        name: String(m.name || mid).slice(0, 120),
      });
    }
    groups.push({ id, name: String(raw.name || id).slice(0, 60), description: String(raw.description || '').slice(0, 200), models });
  }
  const defaultGroupId = groups.some((g) => g.id === input?.defaultGroupId) ? input.defaultGroupId : (groups[0] ? groups[0].id : '');
  return { version: 1, enabled: input?.enabled !== false, defaultGroupId, groups, updatedAt: Date.now() };
}

// ---------------------------------------------------------------------------
// methods
// ---------------------------------------------------------------------------
const methods = {
  'status': () => {
    const home = resolveHome();
    if (!home) return { ok: false, errorCode: 'CINDY_HOME_NOT_FOUND', message: '找不到 Cindy 数据目录（CindyGlobal/pi-package-home）。' };
    const p = pathsFor(home);
    const settings = readSettings(p.settings);
    const injected = settings.json.packages.filter((e) => typeof e === 'string' && samePath(e, p.extDir));
    const config = readConfigFile(p.extConfig);
    return {
      ok: true,
      platform: process.platform,
      home,
      extDir: p.extDir,
      settingsFile: p.settings,
      injected: injected.length === 1,
      duplicateEntries: Math.max(0, injected.length - 1),
      extensionPresent: fs.existsSync(p.extIndex),
      configSource: config ? 'file' : 'default',
      config: config || EMPTY_CONFIG,
      extensionVersion: EXT_VERSION,
    };
  },

  'install': () => {
    const home = resolveHome();
    if (!home) return { ok: false, errorCode: 'CINDY_HOME_NOT_FOUND', message: '找不到 Cindy 数据目录。' };
    const p = pathsFor(home);
    const wrote = [];
    if (ensureFile(p.extIndex, EXT_INDEX.replace(/^\n/, ''))) wrote.push('index.js');
    if (ensureFile(p.extPackage, EXT_PACKAGE + '\n')) wrote.push('package.json');
    const existing = readConfigFile(p.extConfig);
    if (!existing && ensureFile(p.extConfig, JSON.stringify(EMPTY_CONFIG, null, 2) + '\n')) wrote.push('config.json');
    const withConfig = readConfigFile(p.extConfig) ? ['config.json'] : [];
    const entry = injectEntry(p.settings, p.extDir);
    log(JSON.stringify({ install: true, wrote, entry: entry.changed }));
    return {
      ok: true,
      changed: wrote.length > 0 || entry.changed,
      wrote,
      settingsChanged: entry.changed,
      extDir: p.extDir,
      files: [p.extIndex, p.extPackage, ...withConfig.map(() => p.extConfig)],
      note: '扩展在下一个新任务生效。',
    };
  },

  'uninstall': () => {
    const home = resolveHome();
    if (!home) return { ok: false, errorCode: 'CINDY_HOME_NOT_FOUND', message: '找不到 Cindy 数据目录。' };
    const p = pathsFor(home);
    const entry = removeEntry(p.settings, p.extDir);
    let removedDir = false;
    if (fs.existsSync(p.extDir)) {
      fs.rmSync(p.extDir, { recursive: true, force: true });
      removedDir = true;
    }
    return {
      ok: true,
      changed: entry.changed || removedDir,
      settingsChanged: entry.changed,
      removedDir,
      note: '已移除扩展与配置；Cindy 设置页可能需要重新打开才会刷新列表。',
    };
  },

  'config/get': () => {
    const home = resolveHome();
    if (!home) return { ok: false, errorCode: 'CINDY_HOME_NOT_FOUND', message: '找不到 Cindy 数据目录。' };
    const p = pathsFor(home);
    return { ok: true, config: readConfigFile(p.extConfig) || EMPTY_CONFIG };
  },

  'config/set': (params) => {
    const home = resolveHome();
    if (!home) return { ok: false, errorCode: 'CINDY_HOME_NOT_FOUND', message: '找不到 Cindy 数据目录。' };
    const p = pathsFor(home);
    const next = sanitizeConfig(params && params.config ? params.config : params);
    const before = readConfigFile(p.extConfig);
    const changed = !before || JSON.stringify({ ...before, updatedAt: 0 }) !== JSON.stringify({ ...next, updatedAt: 0 });
    if (changed) {
      fs.mkdirSync(p.extDir, { recursive: true });
      ensureFile(p.extConfig, JSON.stringify(next, null, 2) + '\n');
      // force mtime bump so the extension's cache invalidates even for equal-size edits
      const now = new Date();
      fs.utimesSync(p.extConfig, now, now);
    }
    return { ok: true, changed, config: next };
  },
};

const readline = require('node:readline');
readline.createInterface({ input: process.stdin }).on('line', function (line) {
  let request;
  try {
    request = JSON.parse(line);
  } catch (_) {
    reply({ jsonrpc: '2.0', id: null, error: { code: -32700, message: 'Parse error' } });
    return;
  }
  const handler = methods[request.method];
  if (!handler) {
    reply({ jsonrpc: '2.0', id: request.id, error: { code: -32601, message: 'Method not found: ' + request.method } });
    return;
  }
  Promise.resolve()
    .then(() => handler(request.params || {}))
    .then((result) => reply({ jsonrpc: '2.0', id: request.id, result }))
    .catch((err) => reply({ jsonrpc: '2.0', id: request.id, error: { code: -32000, message: (err && err.message) || String(err) } }));
});
